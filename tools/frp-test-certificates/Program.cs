using System;
using System.IO;
using System.Net;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
if(args.Length!=1)throw new ArgumentException("Output directory required.");
var root=Path.GetFullPath(args[0]);
if(Directory.Exists(root)&&Directory.EnumerateFileSystemEntries(root).GetEnumerator().MoveNext())throw new IOException("Refusing a nonempty certificate directory.");
Directory.CreateDirectory(root);
using var caKey=RSA.Create(2048);
var caRequest=new CertificateRequest("CN=ServerWorkbench LOCAL TEST ONLY Root",caKey,HashAlgorithmName.SHA256,RSASignaturePadding.Pkcs1);
caRequest.CertificateExtensions.Add(new X509BasicConstraintsExtension(true,false,0,true));
caRequest.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.KeyCertSign|X509KeyUsageFlags.CrlSign,true));
using var ca=caRequest.CreateSelfSigned(DateTimeOffset.UtcNow.AddHours(-1),DateTimeOffset.UtcNow.AddDays(2));
File.WriteAllText(Path.Combine(root,"ca.pem"),ca.ExportCertificatePem());
using var key=RSA.Create(2048);
var request=new CertificateRequest("CN=localhost",key,HashAlgorithmName.SHA256,RSASignaturePadding.Pkcs1);
request.CertificateExtensions.Add(new X509BasicConstraintsExtension(false,false,0,true));
request.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.DigitalSignature|X509KeyUsageFlags.KeyEncipherment,true));
request.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(new OidCollection{new Oid("1.3.6.1.5.5.7.3.1")},true));
var san=new SubjectAlternativeNameBuilder();san.AddDnsName("localhost");san.AddIpAddress(IPAddress.Loopback);request.CertificateExtensions.Add(san.Build());
using var server=request.Create(ca,DateTimeOffset.UtcNow.AddMinutes(-30),DateTimeOffset.UtcNow.AddDays(1),RandomNumberGenerator.GetBytes(16));
File.WriteAllText(Path.Combine(root,"server.pem"),server.ExportCertificatePem());
File.WriteAllText(Path.Combine(root,"server-key.pem"),key.ExportPkcs8PrivateKeyPem());
using(var privateCert=server.CopyWithPrivateKey(key))File.WriteAllText(Path.Combine(root,"wrapped-private-container.pem"),"-----BEGIN CERTIFICATE-----\n"+Convert.ToBase64String(privateCert.Export(X509ContentType.Pfx,""))+"\n-----END CERTIFICATE-----\n");
using var otherKey=RSA.Create(2048);
var otherRequest=new CertificateRequest("CN=ServerWorkbench Wrong LOCAL TEST Root",otherKey,HashAlgorithmName.SHA256,RSASignaturePadding.Pkcs1);
otherRequest.CertificateExtensions.Add(new X509BasicConstraintsExtension(true,false,0,true));
using var other=otherRequest.CreateSelfSigned(DateTimeOffset.UtcNow.AddHours(-1),DateTimeOffset.UtcNow.AddDays(2));
File.WriteAllText(Path.Combine(root,"wrong-ca.pem"),other.ExportCertificatePem());
File.WriteAllText(Path.Combine(root,".serverworkbench-local-test-only"),"Ephemeral localhost-only certificates; never use for a real public relay.");
Console.WriteLine("Generated ephemeral localhost certificates without changing any system trust store.");
